//! `cargo xtask emoji-data <emoji-test.txt> <cldr-dir>`: write `crates/engine/src/emoji.tsv`,
//! the emoji Insert › Emoji offers.
//!
//! - `emoji-test.txt`: Unicode's list (UTS #51) in its keyboard order, with groups. Only
//!   fully-qualified emoji up to [`MAX_VERSION`] are kept (newer ones have no glyph in the emoji
//!   fonts people have yet). Skin-tone variants become a column of their base emoji.
//! - `<cldr-dir>`: CLDR's annotations, `ann-<lang>.json` and `der-<lang>.json` (cldr-json's
//!   `annotations` and `annotationsDerived`) for English and French: names and keywords.
//!
//! One line per emoji: group, emoji, English name, French name, keywords (`|`), the five
//! skin-tone variants (space separated, or empty). Both sources are under the Unicode License v3.

use std::collections::BTreeMap;
use std::path::Path;

use serde_json::Value;

/// Newest emoji version kept.
const MAX_VERSION: f32 = 15.1;
const GROUPS: [&str; 9] =
    ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink", "Travel & Places", "Activities", "Objects", "Symbols", "Flags"];
const TONES: [char; 5] = ['\u{1F3FB}', '\u{1F3FC}', '\u{1F3FD}', '\u{1F3FE}', '\u{1F3FF}'];

/// CLDR names and keywords by emoji, for one language (plain and derived annotations).
fn cldr(dir: &Path, lang: &str) -> Result<BTreeMap<String, (String, Vec<String>)>, String> {
    let mut out = BTreeMap::new();
    for (file, key) in [(format!("ann-{lang}.json"), "annotations"), (format!("der-{lang}.json"), "annotationsDerived")] {
        let path = dir.join(&file);
        let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let v: Value = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        let Some(map) = v.get(key).and_then(|a| a.get("annotations")).and_then(Value::as_object) else {
            return Err(format!("{}: no {key}.annotations", path.display()));
        };
        for (k, a) in map {
            let list = |f: &str| -> Vec<String> {
                a.get(f).and_then(Value::as_array).map(|v| v.iter().filter_map(Value::as_str).map(str::to_string).collect()).unwrap_or_default()
            };
            let name = list("tts").into_iter().next().unwrap_or_default();
            out.entry(k.replace('\u{FE0F}', "")).or_insert((name, list("default")));
        }
    }
    Ok(out)
}

fn clean(s: &str) -> String {
    s.replace(['\t', '\n', '|'], " ").trim().to_string()
}

pub fn run(root: &Path, args: &[&str]) -> Result<(), String> {
    let [test, dir] = args else { return Err("usage: cargo xtask emoji-data <emoji-test.txt> <cldr-dir>".into()) };
    let text = std::fs::read_to_string(test).map_err(|e| format!("{test}: {e}"))?;
    let (en, fr) = (cldr(Path::new(dir), "en")?, cldr(Path::new(dir), "fr")?);
    // (group, emoji, name from emoji-test) in order, and tone variants by base emoji.
    let mut list: Vec<(usize, String, String)> = Vec::new();
    let mut tones: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut group: Option<usize> = None;
    for line in text.lines() {
        if let Some(g) = line.strip_prefix("# group: ") {
            group = GROUPS.iter().position(|x| *x == g.trim());
            continue;
        }
        let Some(g) = group else { continue };
        let Some((_, rest)) = line.split_once("; fully-qualified") else { continue };
        let Some((_, comment)) = rest.split_once('#') else { continue };
        let mut words = comment.split_whitespace();
        let (Some(emoji), Some(ver)) = (words.next(), words.next()) else { continue };
        let version: f32 = ver.trim_start_matches('E').parse().unwrap_or(99.0);
        if version > MAX_VERSION {
            continue;
        }
        let name = words.collect::<Vec<_>>().join(" ");
        let modifiers: Vec<char> = emoji.chars().filter(|c| TONES.contains(c)).collect();
        if modifiers.is_empty() {
            list.push((g, emoji.to_string(), name));
            continue;
        }
        // A variant in one tone throughout (both people of a couple alike): a tone of its base.
        if modifiers.iter().all(|m| *m == modifiers[0]) {
            let base: String = emoji.chars().filter(|c| !TONES.contains(c)).collect();
            // The base of `👍🏻` is `👍`; of `🫱🏻‍🫲🏻`, `🫱‍🫲`, which the list may write with FE0F.
            tones.entry(base.replace('\u{FE0F}', "")).or_default().push(emoji.to_string());
        }
    }
    let mut out = String::from("# Generated by `cargo xtask emoji-data` from Unicode's emoji-test.txt and CLDR annotations (Unicode License v3).\n");
    out.push_str("# group\temoji\tEnglish name\tFrench name\tkeywords\tskin tones\n");
    let mut n = 0;
    for (g, emoji, name) in &list {
        let key = emoji.replace('\u{FE0F}', "");
        let (en_name, en_kw) = en.get(&key).cloned().unwrap_or_default();
        let (fr_name, fr_kw) = fr.get(&key).cloned().unwrap_or_default();
        let en_name = if en_name.is_empty() { name.clone() } else { en_name };
        let mut kw: Vec<String> = Vec::new();
        for k in en_kw.iter().chain(&fr_kw) {
            let k = clean(&k.to_lowercase());
            if !k.is_empty() && !kw.contains(&k) && k != en_name.to_lowercase() && k != fr_name.to_lowercase() {
                kw.push(k);
            }
        }
        let t = tones.get(&key).filter(|t| t.len() == 5).map(|t| t.join(" ")).unwrap_or_default();
        out.push_str(&format!("{g}\t{emoji}\t{}\t{}\t{}\t{t}\n", clean(&en_name), clean(&fr_name), kw.join("|")));
        n += 1;
    }
    let path = root.join("crates/engine/src/emoji.tsv");
    std::fs::write(&path, out).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("{}: {n} emoji, {} with skin tones", path.display(), tones.values().filter(|t| t.len() == 5).count());
    Ok(())
}
